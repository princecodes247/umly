import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT_DIR = path.resolve(__dirname, '..')
const PUZZLES_DIR = path.join(ROOT_DIR, 'src', 'data', 'puzzles')
const OUTPUT_FILE = path.join(PUZZLES_DIR, 'index.ts')

const DIAGRAM_ORDER = ['use_case', 'er', 'class', 'dfd']
const REQUIRED_FIELDS = [
  'id',
  'title',
  'type',
  'difficulty',
  'category',
  'scenario',
  'goal',
  'learningObjective',
  'hints',
  'solutionExplanation',
  'initialNodes',
  'solutions',
]

const summaries = []
const fileById = {}
const seenIds = new Set()

for (const diagramType of DIAGRAM_ORDER) {
  const dir = path.join(PUZZLES_DIR, diagramType)
  if (!fs.existsSync(dir)) continue

  const files = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()

  const entries = files.map((file) => {
    const fullPath = path.join(dir, file)
    const raw = fs.readFileSync(fullPath, 'utf8')
    const data = JSON.parse(raw)

    for (const field of REQUIRED_FIELDS) {
      if (data[field] === undefined || data[field] === null) {
        throw new Error(`Puzzle ${fullPath} is missing required field "${field}"`)
      }
    }

    if (seenIds.has(data.id)) {
      throw new Error(`Duplicate puzzle id "${data.id}" in ${fullPath}`)
    }
    seenIds.add(data.id)

    return {
      file,
      diagramType: data.diagramType ?? diagramType,
      data,
    }
  })

  entries.sort((a, b) => {
    const numA = typeof a.data.number === 'number' ? a.data.number : Number.MAX_SAFE_INTEGER
    const numB = typeof b.data.number === 'number' ? b.data.number : Number.MAX_SAFE_INTEGER
    if (numA !== numB) return numA - numB
    return a.data.id.localeCompare(b.data.id)
  })

  for (const entry of entries) {
    const number = summaries.length + 1
    summaries.push({
      id: entry.data.id,
      number,
      title: entry.data.title,
      diagramType: entry.diagramType,
      type: entry.data.type,
      difficulty: entry.data.difficulty,
      category: entry.data.category,
      scenario: entry.data.scenario,
    })
    fileById[entry.data.id] = `./puzzles/${diagramType}/${entry.file}`
  }
}

const banner = `// AUTO-GENERATED by scripts/generate-puzzle-index.mjs — do not edit manually.\n`
const content = `${banner}import type { LevelSummary } from '../../types/game'

export const PUZZLE_SUMMARIES: LevelSummary[] = ${JSON.stringify(summaries, null, 2)}

export const PUZZLE_FILE_BY_ID: Record<string, string> = ${JSON.stringify(fileById, null, 2)}
`

fs.writeFileSync(OUTPUT_FILE, content, 'utf8')
console.log(`Generated ${OUTPUT_FILE} (${summaries.length} puzzles)`)

